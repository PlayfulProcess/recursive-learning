#!/usr/bin/env node
/**
 * build-glossary.mjs — render `glossary/terms.json` into `glossary/index.html`.
 * Pure node, no dependencies. `build-site.mjs` runs it too, so one command rebuilds everything:
 *
 *   node scripts/build-site.mjs        (landing + glossary)
 *   node scripts/build-glossary.mjs    (glossary only)
 *
 * terms.json is the canonical source: edit the words there, never in the generated HTML.
 * The page is rendered at build time rather than fetched in the browser, so every term's anchor
 * (#alignment, #what-held, ...) exists in the HTML itself: a deep link from a game or the film
 * lands on the term without waiting for any script, and the page works from file:// too.
 *
 * It refuses to write if an id is duplicated, a term points at an unknown section, or a
 * `related` id does not exist — a broken anchor is the one failure a glossary must not have.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'glossary', 'terms.json');
const OUT = join(ROOT, 'glossary', 'index.html');
const g = JSON.parse(readFileSync(SRC, 'utf8'));

const SPRITE = readFileSync(join(ROOT, 'scripts', 'mark.svg'), 'utf8')
  .replace(/^<!--[\s\S]*?-->\s*/, '').trim();
const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

/* ---- checks: every anchor unique, every link resolvable ---- */
const byId = new Map();
const problems = [];
const ids = [...g.sections.map(s => s.id), ...g.terms.map(t => t.id), g.what_held_example.id];
for (const id of ids) {
  if (!/^[a-z0-9-]+$/.test(id)) problems.push(`id "${id}" is not lowercase-kebab`);
  if (byId.has(id)) problems.push(`duplicate id "${id}"`);
  byId.set(id, true);
}
const sectionIds = new Set(g.sections.map(s => s.id));
const termIds = new Set(g.terms.map(t => t.id));
for (const t of g.terms) {
  if (!sectionIds.has(t.section)) problems.push(`${t.id}: unknown section "${t.section}"`);
  for (const r of t.related || []) if (!termIds.has(r)) problems.push(`${t.id}: related "${r}" does not exist`);
}
if (problems.length) { console.error('glossary: refusing to write\n  ' + problems.join('\n  ')); process.exit(1); }

const termName = new Map(g.terms.map(t => [t.id, t.term]));
const nStd = g.terms.filter(t => t.standard).length;
const WORDS = ['no', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve',
  'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen', 'eighteen', 'nineteen', 'twenty'];
const word = n => WORDS[n] ?? String(n);
const cap = s => s[0].toUpperCase() + s.slice(1);

const termHtml = t => `      <article class="term" id="${esc(t.id)}">
        <h3><a class="self" href="#${esc(t.id)}">${esc(t.term)}</a>
          <span class="tag ${t.standard ? 'std' : 'ours'}">${t.standard ? 'standard' + (t.standard_in ? ' in ' + esc(t.standard_in) : '') : 'ours'}</span></h3>
        <p class="def">${esc(t.definition)}</p>
        ${t.note ? `<p class="note">${esc(t.note)}</p>` : ''}
        ${(t.related || []).length ? `<p class="rel">See also: ${t.related.map(r => `<a href="#${esc(r)}">${esc(termName.get(r))}</a>`).join(' &middot; ')}</p>` : ''}
      </article>`;

const sectionsHtml = g.sections.map(s => {
  const ts = g.terms.filter(t => t.section === s.id);
  return `    <section class="sec" id="${esc(s.id)}" aria-labelledby="${esc(s.id)}-h">
      <h2 id="${esc(s.id)}-h">${esc(s.title)}</h2>
      <p class="blurb">${esc(s.blurb)}</p>
${ts.map(termHtml).join('\n')}
    </section>`;
}).join('\n\n');

const nav = g.sections.map(s => `<a href="#${esc(s.id)}">${esc(s.title)}</a>`).join('\n      ');
const ex = g.what_held_example;
const exRows = ex.rows.map(r => `          <tr><td class="n">${r.step}</td><td>${esc(r.action)}</td><td class="held k-${esc(r.kind)}">${esc(r.held)}</td></tr>`).join('\n');

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Words — a glossary · Recursive Learning</title>
<meta name="description" content="${esc(g.description)}">
<meta name="author" content="PlayfulProcess">
<meta property="og:title" content="Words — a glossary · Recursive Learning">
<meta property="og:description" content="${esc(g.description)}">
<meta property="og:type" content="website">
<meta property="og:url" content="${esc(g.url)}">
<link rel="alternate" type="application/json" href="terms.json">
<!-- Generated by scripts/build-glossary.mjs from glossary/terms.json — edit the JSON, not this. -->
<style>
  :root{
    --bg:#0d0f14; --panel:#151922; --panel2:#1c212c; --line:#2a3140;
    --ink:#e8ecf3; --muted:#8e9aae; --accent:#5ee2b0; --accent-ink:#06281d; --warn:#f0b866;
    --power:#e2725e; --sustain:#7fb2f0; --stop:#c79bf0;
  }
  *{box-sizing:border-box}
  html,body{margin:0;background:var(--bg);color:var(--ink);color-scheme:dark;
    font-family:Inter,system-ui,-apple-system,"Segoe UI",sans-serif;line-height:1.55;
    -webkit-text-size-adjust:100%}
  .wrap{max-width:760px;margin:0 auto;padding-block:28px 64px;padding-left:16px;padding-right:16px}
  a{color:var(--accent)}

  header.mark{display:flex;align-items:center;gap:12px;margin:0 0 14px}
  header.mark svg{width:36px;height:36px;color:var(--accent);opacity:.92;flex:none}
  header.mark a{display:flex;flex:none}
  h1{font-size:23px;line-height:1.18;margin:0;letter-spacing:-.01em}
  h1 .sub{display:block;font-size:12px;font-weight:400;letter-spacing:.14em;
    text-transform:uppercase;color:var(--muted);margin-bottom:4px}
  .lede{font-size:15px;max-width:64ch;margin:0 0 10px}
  .how{font-size:13px;color:var(--muted);max-width:66ch;margin:0 0 18px}
  .how code{font-size:12px;background:var(--panel2);border:1px solid var(--line);border-radius:5px;padding:1px 5px;
    overflow-wrap:anywhere}

  nav.toc{display:flex;flex-wrap:wrap;gap:7px;margin:0 0 26px;padding:0}
  nav.toc a{font-size:13px;text-decoration:none;color:var(--ink);background:var(--panel);
    border:1px solid var(--line);border-radius:999px;padding:5px 12px}
  nav.toc a:hover,nav.toc a:focus-visible{border-color:var(--accent);color:var(--accent)}

  .sec{margin:0 0 30px;scroll-margin-top:16px}
  .sec h2{font-size:12px;letter-spacing:.11em;text-transform:uppercase;color:var(--muted);
    margin:0 0 3px;font-weight:600}
  .blurb{font-size:13px;color:var(--muted);margin:0 0 12px}

  .term{background:var(--panel);border:1px solid var(--line);border-radius:12px;
    padding:13px 15px 12px;margin:0 0 10px;scroll-margin-top:16px;
    transition:border-color .2s ease,background .2s ease}
  .term:target{border-color:var(--accent);background:var(--panel2)}
  .term h3{margin:0;font-size:16.5px;line-height:1.3;display:flex;flex-wrap:wrap;align-items:baseline;gap:4px 10px}
  .term h3 a.self{color:var(--ink);text-decoration:none}
  .term h3 a.self:hover,.term h3 a.self:focus-visible{color:var(--accent);text-decoration:underline}
  .tag{font-size:10.5px;font-weight:600;letter-spacing:.08em;text-transform:uppercase;
    border-radius:999px;padding:2px 8px;border:1px solid var(--line);white-space:nowrap}
  .tag.std{color:var(--sustain);border-color:rgba(127,178,240,.45)}
  .tag.ours{color:var(--accent);border-color:rgba(94,226,176,.4)}
  .def{margin:7px 0 0;font-size:15px}
  .note{margin:6px 0 0;font-size:13.5px;color:var(--muted)}
  .rel{margin:8px 0 0;font-size:12px;color:var(--muted)}

  .example{scroll-margin-top:16px;margin:8px 0 0;border-top:1px solid var(--line);padding-top:18px}
  .example h2{font-size:12px;letter-spacing:.11em;text-transform:uppercase;color:var(--muted);margin:0 0 6px;font-weight:600}
  .example .cap{font-size:13px;color:var(--muted);margin:0 0 12px;max-width:66ch}
  table{width:100%;border-collapse:collapse;font-size:13.5px;table-layout:fixed}
  th,td{text-align:left;vertical-align:top;padding:8px 8px;border-bottom:1px solid var(--line);overflow-wrap:anywhere}
  th{font-size:11px;letter-spacing:.08em;text-transform:uppercase;color:var(--muted);font-weight:600}
  th.n,td.n{width:2.2em;color:var(--muted)}
  th.held{width:38%}
  td.held{font-weight:600}
  .k-inner{color:var(--accent)} .k-outer{color:var(--warn)} .k-presence{color:var(--sustain)} .k-nothing{color:var(--power)}
  @media (max-width:520px){
    table,tbody,tr,td{display:block;width:100%}
    thead{position:absolute;left:-9999px}
    tr{border-bottom:1px solid var(--line);padding:8px 0}
    td{border:0;padding:2px 0}
    td.n{width:auto;font-size:11px;letter-spacing:.08em;text-transform:uppercase}
    td.n::before{content:"Step "}
    td.held::before{content:"held: ";font-weight:400;color:var(--muted)}
  }

  footer{margin-top:36px;padding-top:15px;border-top:1px solid var(--line);color:var(--muted);font-size:12.5px}
</style>
</head>
<body>
<svg width="0" height="0" aria-hidden="true" focusable="false" style="position:absolute;left:-9999px">${SPRITE}</svg>

<div class="wrap">

  <header class="mark">
    <a href="../" aria-label="Recursive Learning — home"><svg viewBox="0 0 100 100" aria-hidden="true"><use href="#spiral"/></svg></a>
    <h1><span class="sub">Recursive Learning</span>Words</h1>
  </header>

  <p class="lede">The words the film and the games lean on, one idea each. ${cap(word(nStd))} are standard
    terms; the other ${word(g.terms.length - nStd)} are ours, marked so. They are working definitions,
    written to be argued with.</p>
  <p class="how">Every term has its own link, so a game card or a frame of the film can point at it:
    <code>learning.recursive.eco/glossary/#what-held</code>. The same words as data:
    <a href="terms.json">terms.json</a>.</p>

  <nav class="toc" aria-label="Sections">
      ${nav}
      <a href="#${esc(ex.id)}">Worked example</a>
  </nav>

${sectionsHtml}

    <section class="example" id="${esc(ex.id)}" aria-labelledby="${esc(ex.id)}-h">
      <h2 id="${esc(ex.id)}-h">${esc(ex.title)}</h2>
      <p class="cap">${esc(ex.caption)} The four answers are the ones <a href="#what-held">what held</a> allows:
        <a href="#guardrail-inner">inner rule</a>, <a href="#guardrail-outer">outer rule</a>, <a href="#presence">presence</a>, or nothing.</p>
      <table>
        <thead><tr><th class="n">#</th><th>Action</th><th class="held">What held</th></tr></thead>
        <tbody>
${exRows}
        </tbody>
      </table>
    </section>

  <footer>PlayfulProcess &middot; <a href="../">Recursive Learning</a> &middot;
    <a href="https://recursive.eco">recursive.eco</a> &middot; text CC BY-SA 4.0 &middot;
    <a href="https://github.com/PlayfulProcess/recursive-learning/blob/main/glossary/terms.json">edit the words</a></footer>

</div>
</body>
</html>
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, html, 'utf8');
console.log(`glossary/index.html written — ${g.terms.length} terms, ${g.sections.length} sections.`);
